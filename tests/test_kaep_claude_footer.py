"""Observed Claude Code trailing-footer interoperability regression.

Fixture captures the real unmodified GitHub PING/ACK comment bodies from
kinoko34077/devflow#503. No network writes, provider launch or model identity
attestation occur in this test.
"""
from __future__ import annotations

import json
from pathlib import Path
import unittest

from tools.kaep_inbox_reader import inspect_pages
from tools.kaep_mailbox_codec import (
    CLAUDE_CODE_FOOTER, InvalidMessage, decode_comment, encode_comment,
    read_mailbox, verify_reply_chain, fingerprint,
)
from tools.kaep_reply_sender import FIXED_ACK, make_reply, post_and_verify, send_reply

REPO = "kinoko34077/devflow"
ISSUE = 503
TASK = REPO + "#503"
PING_ID = "msg_claudem1ping20261013"
ACK_ID = "msg_8487ea7da56862cf59a2c53652107859"
FIXTURE = Path(__file__).parent / "fixtures" / "kaep_m1_claude_ack_observed.json"


def pages():
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def wire():
    return json.dumps(pages(), ensure_ascii=False)


class ClaudeFooterInteropTests(unittest.TestCase):
    def test_exact_observed_footer_only(self):
        p, ack = pages()[0]
        self.assertTrue(p["body"].endswith("\n```"))
        self.assertTrue(ack["body"].endswith(CLAUDE_CODE_FOOTER))
        self.assertEqual(decode_comment(ack["body"], task_ref=TASK)["message_id"], ACK_ID)
        self.assertEqual(decode_comment(p["body"], task_ref=TASK)["message_id"], PING_ID)

    def test_full_existing_m1_mailbox_recovers(self):
        p, ack = pages()[0]
        items = read_mailbox([p, ack], task_ref=TASK)
        self.assertEqual([m["kind"] for _, m in items], ["REQUEST", "ACK"])
        verify_reply_chain([m for _, m in items])
        summary = inspect_pages(wire(), repository=REPO, issue=ISSUE,
                                recipient="chatgpt")
        self.assertEqual([x["message_id"] for x in summary["messages"]], [ACK_ID])
        self.assertFalse(summary["messages"][0]["provider_identity_verified"])

    def test_decoder_does_not_strip_suffix_inside_payload(self):
        ack = decode_comment(pages()[0][1]["body"], task_ref=TASK)
        self.assertEqual(ack["kind"], "ACK")
        self.assertNotIn("Generated by", ack["payload"]["text"])

    def test_original_encoder_remains_strict_canonical(self):
        ack = decode_comment(pages()[0][1]["body"], task_ref=TASK)
        canonical = encode_comment(ack)
        self.assertFalse(canonical.endswith(CLAUDE_CODE_FOOTER))
        self.assertEqual(decode_comment(canonical), ack)

    def test_repeated_identical_ack_is_detected_not_reposted(self):
        result = send_reply(
            repository=REPO, issue=ISSUE, parent_message_id=PING_ID,
            kind="ACK", response_text=FIXED_ACK,
            expect_actor="kinoko34077", offline_pages=wire(),
        )
        self.assertEqual(result["status"], "ALREADY_SENT")
        self.assertEqual(result["message_id"], ACK_ID)
        self.assertEqual(result["posted_comment_id"], 6159903731)
        self.assertFalse(result["genuine_claude_identity_verified"])

    def test_post_readback_with_exact_decorated_comment(self):
        ping, ack = pages()[0]
        reply = decode_comment(ack["body"], task_ref=TASK)
        result_id = post_and_verify(
            repository=REPO, issue=ISSUE, message=reply,
            post_func=lambda **_: ack["id"],
            fetch_func=lambda repo, issue: wire(),
            expected_post_actor="kinoko34077",
        )
        self.assertEqual(result_id, 6159903731)

    def test_footer_variations_and_junk_fail_closed(self):
        body = pages()[0][1]["body"]
        original = body.removesuffix(CLAUDE_CODE_FOOTER)
        bads = [
            original + "\nwhatever",
            original + "\n\n---\n_Generated by Claude Code_",
            original + CLAUDE_CODE_FOOTER + "\n",
            original + CLAUDE_CODE_FOOTER + " extra",
            original + CLAUDE_CODE_FOOTER * 2,
            original + "\nunknown\n" + CLAUDE_CODE_FOOTER,
            original + "\n\n---\n_Generated by [Claude Code](https://phishing.example)_",
            original.replace("<!-- kaep:message:v0.2 -->",
                             "<!-- kaep:message:v0.1 -->") + CLAUDE_CODE_FOOTER,
        ]
        for bad in bads:
            with self.subTest(bad_tail=bad[-70:]):
                with self.assertRaisesRegex(InvalidMessage, "INVALID_WRAPPER"):
                    decode_comment(bad, task_ref=TASK)

    def test_malformed_inner_json_is_not_excused_by_footer(self):
        valid = pages()[0][1]["body"]
        invalid = valid.replace('"kind": "ACK"', '"kind": "ACK",\n  "kind": "BLOCKED"')
        with self.assertRaisesRegex(InvalidMessage, "DUPLICATE_JSON_KEY"):
            decode_comment(invalid, task_ref=TASK)

    def test_transport_footer_does_not_bypass_max_comment_size(self):
        ack = pages()[0][1]["body"]
        malformed = ack[:-len(CLAUDE_CODE_FOOTER)] + (" " * 8192) + CLAUDE_CODE_FOOTER
        with self.assertRaisesRegex(InvalidMessage, "COMMENT_TOO_LARGE"):
            decode_comment(malformed, task_ref=TASK)

    def test_future_answer_like_reply_parses_with_same_footer(self):
        ping, _ = pages()[0]
        ack = decode_comment(pages()[0][1]["body"], task_ref=TASK)
        answer, none = make_reply(
            wire(), repository=REPO, issue=ISSUE,
            parent_message_id=PING_ID, kind="ANSWER",
            response_text="Actual Claude evidence to be supplied by Claude only.",
            expect_actor="kinoko34077",
        )
        self.assertIsNone(none)
        next_body = encode_comment(answer) + CLAUDE_CODE_FOOTER
        self.assertEqual(decode_comment(next_body, task_ref=TASK), answer)
        answer_comment = {"id": 6159903732, "body": next_body,
                          "user": {"login": "kinoko34077"}}
        items = read_mailbox([ping, pages()[0][1], answer_comment], task_ref=TASK)
        verify_reply_chain([m for _, m in items])
        self.assertEqual([m["kind"] for _, m in items], ["REQUEST", "ACK", "ANSWER"])


if __name__ == "__main__":
    unittest.main()
